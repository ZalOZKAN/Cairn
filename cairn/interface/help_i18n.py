_ORDER = ("tr", "fr", "es", "de", "zh", "ja")


def localize(app, lang: str) -> None:
    """Swap each command's help for its translation, before Typer builds the CLI."""
    if lang not in _ORDER:
        return
    idx = _ORDER.index(lang)

    def walk(typer_app, prefix: str) -> None:
        for cmd in typer_app.registered_commands:
            name = cmd.name or cmd.callback.__name__.replace("_", "-")
            entry = HELP.get(f"{prefix}{name}")
            if entry:
                cmd.help = entry[idx]
        for group in typer_app.registered_groups:
            entry = HELP.get(f"{prefix}{group.name}")
            if entry:
                group.help = entry[idx]
                group.typer_instance.info.help = entry[idx]
            walk(group.typer_instance, f"{prefix}{group.name} ")

    walk(app, "")
    if "" in HELP:
        app.info.help = HELP[""][idx]
